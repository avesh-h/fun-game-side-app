/**
 * Pick a random word pair, avoiding indices already used this session.
 * Returns the pair and its index in the bank.
 */
export function pickWordPair(
  usedIndices: readonly number[],
): { pair: WordPair; index: number } {
  const available = WORD_BANK
    .map((pair, index) => ({ pair, index }))
    .filter(({ index }) => !usedIndices.includes(index))

  // If somehow all words have been used, reset and pick from the full bank.
  const pool = available.length > 0 ? available : WORD_BANK.map((pair, index) => ({ pair, index }))
  const pick = pool[Math.floor(Math.random() * pool.length)]!
  return { pair: pick.pair, index: pick.index }
}
